import os
import subprocess
from datetime import datetime
from pathlib import Path

# Projects live outside the gemforge repo.
# Override by setting PROJECTS_ROOT in .env
_REPO_ROOT = Path(__file__).parent.parent.resolve()
PROJECTS_ROOT = Path(os.getenv("PROJECTS_ROOT", str(_REPO_ROOT.parent / "gemforge-projects")))

def ensure_dir(path: str):
    os.makedirs(path, exist_ok=True)
    return path

def write_file(path: str, content: str):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return path

def run_command(cmd: list, cwd: str = None):
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"⚠️ Command failed: {' '.join(cmd)}")
        print(result.stderr)
    return result

def init_git_repo(repo_path: str):
    ensure_dir(repo_path)
    run_command(["git", "init"], cwd=repo_path)
    run_command(["git", "branch", "-M", "main"], cwd=repo_path)
    return repo_path

def create_project_structure(gem_name: str):
    timestamp = datetime.now().strftime("%Y%m%d")
    clean_name = "".join(c if c.isalnum() else "-" for c in gem_name.lower())
    full_path = str(PROJECTS_ROOT / f"{clean_name}-{timestamp}")

    ensure_dir(full_path)
    # full_path is always absolute at this point

    # Create canonical files
    write_file(f"{full_path}/MASTERBRIEF.md", "# MASTERBRIEF\n\nGenerated by GemForge.")
    write_file(f"{full_path}/PRD.md", "# PRD\n\n(Will be filled by next agents)")
    write_file(f"{full_path}/PERSISTENT.md", "# PERSISTENT.md\n\nThis is the AI operating manual for this project.")
    write_file(f"{full_path}/progress.txt", f"Project created: {datetime.now()}\nPhase: Bootstrapped\n")
    write_file(f"{full_path}/README.md", f"# {gem_name}\n\nBuilt with GemForge.")

    # Git
    init_git_repo(full_path)
    run_command(["git", "add", "."], cwd=full_path)
    run_command(["git", "commit", "-m", "chore: initial scaffold by GemForge Bootstrapper"], cwd=full_path)

    print(f"✅ Real project created at: {full_path}")
    return full_path
