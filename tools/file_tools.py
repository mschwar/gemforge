import os
import subprocess
from datetime import datetime
from pathlib import Path

# Projects live outside the gemforge repo.
# Override by setting PROJECTS_ROOT in .env
_REPO_ROOT = Path(__file__).parent.parent.resolve()
PROJECTS_ROOT = Path(os.getenv("PROJECTS_ROOT", str(_REPO_ROOT.parent / "gemforge-projects")))


class CommandFailure(RuntimeError):
    """Raised when a critical subprocess command fails."""

    def __init__(self, payload: dict):
        self.payload = payload
        message = payload.get("message", "Critical command failed")
        super().__init__(message)


def ensure_dir(path: str):
    os.makedirs(path, exist_ok=True)
    return path

def write_file(path: str, content: str):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return path

def run_command(
    cmd: list,
    cwd: str = None,
    *,
    critical: bool = False,
    error_code: str = "",
    error_stage: str = "",
    operator_action: str = "",
):
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"⚠️ Command failed: {' '.join(cmd)}")
        print(result.stderr)
        if critical:
            payload = {
                "message": f"Critical command failed: {' '.join(cmd)}",
                "error_code": error_code or "CRITICAL_COMMAND_FAILED",
                "error_stage": error_stage or "command",
                "operator_action": operator_action or "Inspect stderr and fix environment prerequisites.",
                "command": " ".join(cmd),
                "returncode": result.returncode,
                "stderr": (result.stderr or "").strip(),
            }
            raise CommandFailure(payload)
    return result

def init_git_repo(repo_path: str):
    ensure_dir(repo_path)
    run_command(
        ["git", "init"],
        cwd=repo_path,
        critical=True,
        error_code="GIT_INIT_FAILED",
        error_stage="bootstrapper",
        operator_action="Install git and verify repository permissions.",
    )
    run_command(
        ["git", "branch", "-M", "main"],
        cwd=repo_path,
        critical=True,
        error_code="GIT_BRANCH_SETUP_FAILED",
        error_stage="bootstrapper",
        operator_action="Verify git repo state and retry branch setup.",
    )
    return repo_path


def _timestamp_for_project() -> str:
    return datetime.now().strftime("%Y%m%d-%H%M%S")


def create_project_structure(gem_name: str):
    timestamp = _timestamp_for_project()
    clean_name = "".join(c if c.isalnum() else "-" for c in gem_name.lower()).strip("-") or "new-gem"

    candidate = PROJECTS_ROOT / f"{clean_name}-{timestamp}"
    suffix = 1
    while candidate.exists():
        candidate = PROJECTS_ROOT / f"{clean_name}-{timestamp}-{suffix}"
        suffix += 1

    full_path = str(candidate)

    ensure_dir(full_path)
    # full_path is always absolute at this point

    # Create canonical files
    write_file(f"{full_path}/MASTERBRIEF.md", "# MASTERBRIEF\n\nGenerated by GemForge.")
    write_file(f"{full_path}/PRD.md", "# PRD\n\n(Will be filled by next agents)")
    write_file(f"{full_path}/PERSISTENT.md", "# PERSISTENT.md\n\nThis is the AI operating manual for this project.")
    write_file(f"{full_path}/progress.txt", f"Project created: {datetime.now()}\nPhase: Bootstrapped\n")
    write_file(f"{full_path}/README.md", f"# {gem_name}\n\nBuilt with GemForge.")

    # Git
    init_git_repo(full_path)
    run_command(
        ["git", "add", "."],
        cwd=full_path,
        critical=True,
        error_code="GIT_STAGE_FAILED",
        error_stage="bootstrapper",
        operator_action="Resolve git index/permissions issues, then rerun.",
    )
    run_command(
        ["git", "commit", "-m", "chore: initial scaffold by GemForge Bootstrapper"],
        cwd=full_path,
        critical=True,
        error_code="GIT_BOOTSTRAP_COMMIT_FAILED",
        error_stage="bootstrapper",
        operator_action="Configure git user.name/user.email and rerun.",
    )

    print(f"✅ Real project created at: {full_path}")
    return full_path
